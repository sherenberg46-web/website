/**
 * Безопасная сериализация JSON-LD для <script type="application/ld+json">.
 *
 * JSON.stringify не экранирует «<», и строка «</script>» внутри данных
 * закрывает тег раньше времени — всё, что дальше, браузер выполнит как код.
 * В разметку товара попадают отзывы покупателей (имя и текст), поэтому один
 * одобренный отзыв с «</script><script>…» выполнял бы чужой код у каждого
 * посетителя карточки. Экранируем <, >, & и разделители строк — для JSON это
 * те же символы, поисковики читают разметку как раньше.
 */
export function jsonLd(data: unknown): string {
  return JSON.stringify(data)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}
