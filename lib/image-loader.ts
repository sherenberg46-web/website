/**
 * Загрузчик картинок вместо встроенного оптимизатора Next.
 *
 * Зачем: `next/image` по умолчанию проксирует каждую обложку через свой
 * оптимизатор на sharp. Тот держит крупные буферы в памяти, а память —
 * это 96 % счёта Railway ($8.03 из $8.35 за полмесяца, при том что CPU
 * стоил 6 центов). На каталоге в сорок тысяч обложек оптимизатор и был
 * основным едоком.
 *
 * Обложки и так лежат на CDN PlayStation, который умеет отдавать нужный
 * размер по параметру `w`. Поэтому просто просим у него готовое превью, а
 * Next не обрабатывает картинки вовсе: sharp не загружается, память не растёт.
 *
 * Размеры при этом сохраняются — srcset и `sizes` в компонентах продолжают
 * работать, Next подставит в loader нужную ширину.
 */

interface LoaderArgs {
  src: string;
  width: number;
  quality?: number;
}

export default function psImageLoader({ src, width }: LoaderArgs): string {
  // Локальная статика из public/ — отдаём как есть.
  if (src.startsWith('/')) return src;

  try {
    const url = new URL(src);
    // PS CDN понимает ?w=; на остальных хостах параметр просто игнорируется
    // и приходит оригинал — хуже, чем было, не станет.
    url.searchParams.set('w', String(width));
    return url.toString();
  } catch {
    return src;
  }
}
