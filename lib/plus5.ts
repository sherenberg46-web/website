/**
 * Акция «PLUS5»: скидка 5 % на первую покупку, неделя с запуска.
 *
 * Почему алиас, а не обычный промокод: сервер умеет только одноразовые коды,
 * которые генерирует сам (за брошенную корзину, персональные в боте) — код
 * с произвольным именем создать нельзя. Поэтому сайт принимает PLUS5 от
 * покупателя, молча просит у сервера настоящий одноразовый код 5 % и
 * подставляет его в заказ: скидку считает сам сервер, как обычно.
 *
 * «Первая покупка» контролируется в пределах браузера: после успешного
 * заказа с PLUS5 ставим отметку, и код для этого браузера больше не
 * срабатывает. Строже без привязки к аккаунту не сделать — почту и телефон
 * до заказа мы не знаем, а сервер такой проверки не умеет.
 *
 * После PLUS5_UNTIL алиас отключается: введённый PLUS5 уходит на обычную
 * серверную проверку и получает честное «код не найден».
 */

export const PLUS5_CODE = 'PLUS5';

/** Конец акции — неделя с запуска (22–29 августа 2026, по Минску). */
export const PLUS5_UNTIL = '2026-08-29T23:59:59+03:00';

const USED_KEY = 'gamestore-plus5-used';

export function plus5Active(): boolean {
  return Date.now() < new Date(PLUS5_UNTIL).getTime();
}

/** Может ли этот браузер применить PLUS5 (акция жива, код ещё не использован). */
export function plus5Available(): boolean {
  if (typeof window === 'undefined') return false;
  if (!plus5Active()) return false;
  try {
    return !window.localStorage.getItem(USED_KEY);
  } catch {
    // Приватный режим без доступа к хранилищу — не блокируем скидку.
    return true;
  }
}

/** Заказ с PLUS5 успешно ушёл — больше этот браузер скидку не получает. */
export function markPlus5Used(): void {
  try {
    window.localStorage.setItem(USED_KEY, String(Date.now()));
  } catch {
    /* не критично */
  }
}
