/**
 * Акция «LEVEL5»: скидка 5 % на игры до 4 сентября 2026.
 *
 * Устроена так же, как PLUS5 (см. lib/plus5.ts): сервер умеет только
 * одноразовые коды, которые генерирует сам, поэтому сайт принимает LEVEL5
 * от покупателя, молча просит у сервера настоящий одноразовый код 5 % и
 * подставляет его в заказ. Скидку считает сервер, как обычно.
 *
 * Отличия от PLUS5:
 *  — акция не «на первую покупку», ограничения по браузеру нет;
 *  — действует только на игры: сервер считает скидку от всей корзины,
 *    поэтому корзину с подписками/пополнениями код просто не принимает
 *    (проверка в OrderForm), иначе скидка легла бы и на них.
 *
 * После LEVEL5_UNTIL алиас отключается: введённый LEVEL5 уходит на обычную
 * серверную проверку и получает честное «код не найден».
 */

export const LEVEL5_CODE = 'LEVEL5';

/** Конец акции — 4 сентября 2026 включительно, по Минску. */
export const LEVEL5_UNTIL = '2026-09-04T23:59:59+03:00';

export function level5Active(): boolean {
  return Date.now() < new Date(LEVEL5_UNTIL).getTime();
}
