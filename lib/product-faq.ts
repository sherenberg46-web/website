/**
 * Вопросы к карточке товара.
 *
 * Это не украшение страницы, а перенос работы менеджера на сайт: те же
 * четыре-пять вопросов задают в переписке перед каждой первой покупкой —
 * про аккаунт, про сроки, про «что если не сработает» и про оплату. Пока
 * ответы жили только на страницах «Как купить» и «Гарантии», покупатель либо
 * уходил их искать, либо писал менеджеру, либо не покупал.
 *
 * Ответы короче, чем на странице «Как купить», и это намеренно: здесь нужен
 * ответ, а не статья. Полная версия — по ссылке в блоке условий у цены.
 *
 * Разметку FAQPage сюда НЕ добавляем, хотя соблазн есть. Один и тот же набор
 * вопросов на сорока трёх тысячах карточек — это ровно тот случай, который
 * поисковики считают штампованной разметкой; на главной и на «Как купить»
 * она стоит по делу, а тут навредила бы обеим.
 */
import type { FaqItem } from './faq';

interface Options {
  region: 'UA' | 'TR';
  isPreorder: boolean;
  hasEditions: boolean;
}

export function productFaq({ region, isPreorder, hasEditions }: Options): FaqItem[] {
  const country = region === 'TR' ? 'турецкий' : 'украинский';
  const countryName = region === 'TR' ? 'Турции' : 'Украины';

  const items: FaqItem[] = [
    {
      q: 'Смогу играть со своего аккаунта?',
      a: `Да. Игра покупается на аккаунт региона ${countryName}, но свой основной аккаунт менять не нужно: на консоли живут оба сразу. Ваш прежний остаётся со всеми играми и трофеями, рядом добавляется второй, для покупок. Переключение между ними — обычная смена пользователя.`,
    },
    {
      q: 'Можно ли поменять регион у моего аккаунта?',
      a: 'Нет, страна аккаунта задаётся при регистрации и потом не меняется — это правило PlayStation Network, а не магазина. Поэтому и нужен второй аккаунт: создаётся он за пять минут, помогаем с этим бесплатно.',
    },
    {
      q: isPreorder ? 'Когда я получу игру?' : 'Когда придёт код?',
      a: isPreorder
        ? 'Доступ выдаём к дате выхода игры, а не в момент оплаты. Оплата сегодня закрепляет за вами цену предзаказа. Дату назначает издатель и может её перенести — тогда сдвинется и выдача.'
        : 'В рабочее время — с 10:00 до 22:00 — обычно около 30 минут после оформления заказа. Заказы, сделанные ночью, обрабатываем с утра.',
    },
    {
      q: 'А если код не сработает?',
      a: 'Заменим или вернём деньги — обратиться можно в течение 48 часов. Чаще всего причина простая: код вводят под аккаунтом другого региона, и это решается за минуту. Возврат невозможен только в одном случае — код уже успешно активирован.',
    },
    {
      q: 'Как оплатить?',
      a: 'Переводом на карту (VISA, MasterCard, Белкарт) или через ЕРИП, в белорусских рублях. Оплата — после того, как менеджер подтвердит заказ. Цена на сайте окончательная: ни конвертации, ни комиссий сверху.',
    },
  ];

  if (hasEditions) {
    items.splice(2, 0, {
      q: 'Чем издания отличаются друг от друга?',
      a: `Состав каждого издания перечислен прямо под выбором: обычно это сама игра плюс дополнения, валюта или бонусы. Рядом с ценой показана доплата к самому дешёвому изданию, чтобы разницу не приходилось считать в уме. Все издания — из ${country} каталога и активируются на одном и том же аккаунте.`,
    });
  }

  return items;
}
