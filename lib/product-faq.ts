/**
 * Вопросы к карточке товара.
 *
 * Это не украшение страницы, а перенос работы менеджера на сайт: те же
 * четыре-пять вопросов задают в переписке перед каждой первой покупкой —
 * про аккаунт, про сроки, про «что если не сработает» и про оплату. Пока
 * ответы жили только на страницах «Как купить» и «Гарантии», покупатель либо
 * уходил их искать, либо писал менеджеру, либо не покупал.
 *
 * Ответы короче, чем на странице «Как купить», и это намеренно: здесь нужен
 * ответ, а не статья. Полная версия — по ссылке в блоке условий у цены.
 *
 * Разметку FAQPage сюда НЕ добавляем, хотя соблазн есть. Один и тот же набор
 * вопросов на сорока трёх тысячах карточек — это ровно тот случай, который
 * поисковики считают штампованной разметкой; на главной и на «Как купить»
 * она стоит по делу, а тут навредила бы обеим.
 */
import type { FaqItem } from './faq';

interface Options {
  region: 'UA' | 'TR';
  isPreorder: boolean;
  hasEditions: boolean;
  /** Что известно про русский: озвучка, только субтитры, нет, или неизвестно. */
  russian?: 'audio' | 'subs' | 'none' | null;
  /**
   * Тип товара. Определяет способ выдачи, а он у нас разный:
   *
   * игры и дополнения — менеджер заходит в аккаунт покупателя и покупает
   * игру там, она просто появляется в библиотеке; никакого кода нет и
   * вводить нечего;
   *
   * пополнение кошелька — наоборот, это именно код, который покупатель
   * активирует сам.
   *
   * Вопросы «а если код не сработает» на карточке игры — это ответ не на
   * тот вопрос: покупателя там волнует, зачем нам пароль от аккаунта и что
   * с ним будет после покупки.
   */
  productType?: string | null;
}

export function productFaq({
  region,
  isPreorder,
  hasEditions,
  russian,
  productType,
}: Options): FaqItem[] {
  const isTopup = productType === 'topup';
  const country = region === 'TR' ? 'турецкий' : 'украинский';
  const countryName = region === 'TR' ? 'Турции' : 'Украины';

  const items: FaqItem[] = [
    {
      q: 'Смогу играть со своего аккаунта?',
      a: `Да. Игра покупается на аккаунт региона ${countryName}, но свой основной аккаунт менять не нужно: на консоли живут оба сразу. Ваш прежний остаётся со всеми играми и трофеями, рядом добавляется второй, для покупок. Переключение между ними — обычная смена пользователя.`,
    },
    {
      q: 'Можно ли поменять регион у моего аккаунта?',
      a: 'Нет, страна аккаунта задаётся при регистрации и потом не меняется — это правило PlayStation Network, а не магазина. Поэтому и нужен второй аккаунт: создаётся он за пять минут, помогаем с этим бесплатно.',
    },
    {
      q: isPreorder
        ? 'Когда я получу игру?'
        : isTopup
          ? 'Когда придёт код пополнения?'
          : 'Как я получу игру?',
      a: isPreorder
        ? 'Доступ выдаём к дате выхода игры, а не в момент оплаты. Оплата сегодня закрепляет за вами цену предзаказа. Дату назначает издатель и может её перенести — тогда сдвинется и выдача.'
        : isTopup
          ? 'В рабочее время — с 10:00 до 22:00 — обычно около 30 минут после оформления заказа. Заказы, сделанные ночью, обрабатываем с утра. Код приходит в Telegram, активируете его сами.'
          : 'Менеджер зайдёт в ваш аккаунт PlayStation и купит игру на нём — она появится в библиотеке, останется только скачать. Никаких кодов вводить не нужно. В рабочее время с 10:00 до 22:00 это обычно занимает около 30 минут; заказы, сделанные ночью, обрабатываем с утра.',
    },
    isTopup
      ? {
          q: 'А если код не сработает?',
          a: 'Заменим или вернём деньги — обратиться можно в течение 48 часов. Чаще всего причина простая: код вводят под аккаунтом другого региона, и это решается за минуту. Возврат невозможен только в одном случае — код уже успешно активирован.',
        }
      : {
          q: 'Зачем нужен пароль от аккаунта и что с ним будет потом?',
          a: 'Игру покупает менеджер, зайдя в ваш аккаунт, — иначе она не окажется в вашей библиотеке. Пароль нужен только на время покупки: сразу после неё его можно сменить, игра останется на аккаунте навсегда. Если вводить пароль на сайте не хотите — оставьте поле пустым, менеджер запросит его в переписке.',
        },
    {
      q: 'А если что-то пойдёт не так?',
      a: isTopup
        ? 'Напишите менеджеру в Telegram — разберёмся. Замена или возврат в течение 48 часов.'
        : 'Напишите менеджеру в Telegram — разберёмся. Если игра не появилась в библиотеке или что-то пошло не так по нашей вине, вернём деньги. Обратиться можно в течение 48 часов.',
    },
    {
      q: 'Как оплатить?',
      a: 'Переводом на карту (VISA, MasterCard, Белкарт) или через ЕРИП, в белорусских рублях. Оплата — после того, как менеджер подтвердит заказ. Цена на сайте окончательная: ни конвертации, ни комиссий сверху.',
    },
  ];

  // Про язык спрашивают ровно так же часто, как про аккаунт, — но только
  // если нам есть что ответить. Когда языки у карточки не собраны, вопроса
  // не задаём: обещать «уточните у менеджера» в списке частых вопросов
  // значит расписаться в том, что ответа нет.
  if (russian) {
    const answer =
      russian === 'audio'
        ? 'Да, у игры есть русская озвучка — полный список языков указан выше на этой странице. Язык выбирается в настройках игры и от региона аккаунта не зависит.'
        : russian === 'subs'
          ? 'Русские субтитры есть, озвучка — на другом языке. Полный список указан выше на этой странице. Язык выбирается в настройках игры и от региона аккаунта не зависит.'
          : 'У этой игры русского языка нет — ни озвучки, ни субтитров. Полный список языков указан выше на этой странице, чтобы это было видно до покупки, а не после.';
    items.splice(1, 0, { q: 'Игра будет на русском языке?', a: answer });
  }

  if (hasEditions) {
    items.splice(2, 0, {
      q: 'Чем издания отличаются друг от друга?',
      a: `Состав каждого издания перечислен прямо под выбором: обычно это сама игра плюс дополнения, валюта или бонусы. Рядом с ценой показана доплата к самому дешёвому изданию, чтобы разницу не приходилось считать в уме. Все издания — из ${country} каталога и покупаются на один и тот же аккаунт.`,
    });
  }

  return items;
}
